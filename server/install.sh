#!/usr/bin/env bash
# =============================================================================
#  Belle apps server - one-shot installer
#  Supported: Ubuntu 22.04 / 24.04, Debian 12 (x86_64). Run as a normal user
#  with sudo rights, from inside the server folder:
#
#      bash install.sh                 # default: port 3000 behind Caddy on :80
#      bash install.sh --no-caddy      # Node listens on 127.0.0.1 only, bring your own proxy
#      bash install.sh --port 3100     # internal Node port
#
#  Re-running is safe: every step checks what is already there.
#  What it does:
#    1. swap file (if RAM < 2 GB)          5. yt-dlp (E6Tube video conversion)
#    2. ffmpeg, curl, build tools           6. npm dependencies
#    3. Node.js 20                          7. random server password (.bellekey)
#    4. Google Chrome (WhatsApp Web,        8. pm2 service (auto start on boot)
#       server browser, reading mode)       9. Caddy reverse proxy on port 80
# =============================================================================
set -euo pipefail

APP_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PORT=3000
USE_CADDY=1
while [ $# -gt 0 ]; do
  case "$1" in
    --port) PORT="$2"; shift 2 ;;
    --no-caddy) USE_CADDY=0; shift ;;
    -h|--help) sed -n '2,20p' "$0"; exit 0 ;;
    *) echo "Unknown option: $1"; exit 1 ;;
  esac
done

export DEBIAN_FRONTEND=noninteractive
step() { printf '\n\033[1;32m== %s ==\033[0m\n' "$*"; }
ARCH="$(dpkg --print-architecture)"

step "Checking system"
. /etc/os-release
echo "OS: $PRETTY_NAME ($ARCH), folder: $APP_DIR"
if [ ! -f "$APP_DIR/server.js" ]; then echo "server.js not found next to install.sh"; exit 1; fi
sudo -v

step "Swap"
MEM_MB=$(awk '/MemTotal/ {print int($2/1024)}' /proc/meminfo)
if [ "$MEM_MB" -lt 2000 ] && ! swapon --show | grep -q /swapfile; then
  [ -f /swapfile ] || { sudo fallocate -l 2G /swapfile; sudo chmod 600 /swapfile; sudo mkswap /swapfile; }
  sudo swapon /swapfile || true
  grep -q '/swapfile' /etc/fstab || echo '/swapfile none swap sw 0 0' | sudo tee -a /etc/fstab >/dev/null
  echo "2 GB swap enabled (RAM: ${MEM_MB} MB)"
else
  echo "not needed (RAM: ${MEM_MB} MB)"
fi

step "System packages"
sudo apt-get update -y
sudo apt-get install -y ca-certificates curl gnupg ffmpeg python3 build-essential fonts-noto-color-emoji fonts-dejavu

step "Node.js 20"
if ! command -v node >/dev/null || [ "$(node -v | cut -d. -f1 | tr -d v)" -lt 20 ]; then
  curl -fsSL https://deb.nodesource.com/setup_20.x | sudo -E bash -
  sudo apt-get install -y nodejs
fi
node -v

step "Google Chrome"
CHROME_PATH=/usr/bin/google-chrome
if [ "$ARCH" = "amd64" ]; then
  if [ ! -x "$CHROME_PATH" ]; then
    curl -fsSL https://dl.google.com/linux/linux_signing_key.pub | sudo gpg --dearmor --yes -o /usr/share/keyrings/google-chrome.gpg
    echo "deb [arch=amd64 signed-by=/usr/share/keyrings/google-chrome.gpg] http://dl.google.com/linux/chrome/deb/ stable main" | sudo tee /etc/apt/sources.list.d/google-chrome.list >/dev/null
    sudo apt-get update -y
    sudo apt-get install -y google-chrome-stable
  fi
else
  # ARM servers: Google Chrome is not available, use Chromium
  sudo apt-get install -y chromium || sudo apt-get install -y chromium-browser
  CHROME_PATH="$(command -v chromium || command -v chromium-browser)"
fi
echo "browser: $CHROME_PATH"

step "yt-dlp (E6Tube)"
mkdir -p "$HOME/bin"
if [ ! -x "$HOME/bin/yt-dlp" ]; then
  curl -fsSL https://github.com/yt-dlp/yt-dlp/releases/latest/download/yt-dlp -o "$HOME/bin/yt-dlp"
  chmod +x "$HOME/bin/yt-dlp"
else
  "$HOME/bin/yt-dlp" -U || true
fi

step "npm dependencies"
cd "$APP_DIR"
export PUPPETEER_SKIP_DOWNLOAD=true
npm install --omit=dev --no-audit --no-fund
mkdir -p data media

step "Server password"
if [ ! -s "$APP_DIR/.bellekey" ]; then
  head -c 32 /dev/urandom | base64 | tr -dc 'A-Za-z0-9' | head -c 20 > "$APP_DIR/.bellekey"
  echo "new password created"
else
  echo "keeping existing password"
fi
chmod 600 "$APP_DIR/.bellekey"

step "pm2 service"
cat > "$APP_DIR/ecosystem.config.js" <<EOF
// Generated by install.sh. The password is read from .bellekey at start (never commit .bellekey).
module.exports = {
  apps: [{
    name: "belle-server",
    script: "server.js",
    cwd: "$APP_DIR",
    max_memory_restart: "900M",
    env: {
      PORT: "$PORT",
      BELLE_KEY: require("fs").readFileSync("$APP_DIR/.bellekey", "utf8").trim(),
      CHROME_PATH: "$CHROME_PATH",
      YTDLP_PATH: "$HOME/bin/yt-dlp",
      CHAT_LIMIT: "10",          // chats sent to the phone per page
      MSG_LIMIT: "50",           // messages per chat
      KEEP_PER_CHAT: "50",       // messages kept on the server per chat
      GROUP_FILTER: "",          // show only groups whose name contains this word ("" = all groups)
      BELLE_LANG: ""                // "en" / "tr" forces the language of server messages and web pages ("" = automatic)
    }
  }]
};
EOF
if ! command -v pm2 >/dev/null; then sudo npm install -g pm2 --no-audit --no-fund; fi
pm2 startOrReload "$APP_DIR/ecosystem.config.js" --update-env
pm2 save
sudo env PATH="$PATH" pm2 startup systemd -u "$USER" --hp "$HOME" >/dev/null || true

if [ "$USE_CADDY" = "1" ]; then
  step "Caddy (port 80 -> 127.0.0.1:$PORT)"
  if ! command -v caddy >/dev/null; then
    sudo apt-get install -y debian-keyring debian-archive-keyring apt-transport-https
    curl -1sLf 'https://dl.cloudsmith.io/public/caddy/stable/gpg.key' | sudo gpg --dearmor --yes -o /usr/share/keyrings/caddy-stable-archive-keyring.gpg
    curl -1sLf 'https://dl.cloudsmith.io/public/caddy/stable/debian.deb.txt' | sudo tee /etc/apt/sources.list.d/caddy-stable.list >/dev/null
    sudo apt-get update -y
    sudo apt-get install -y caddy
  fi
  # Plain HTTP on purpose: stock Symbian phones cannot negotiate modern TLS (see docs/TLS_PATCH.md).
  # Every request is protected by the server password instead.
  sudo tee /etc/caddy/Caddyfile >/dev/null <<EOF
{
	auto_https off
}
:80 {
	encode gzip
	reverse_proxy 127.0.0.1:$PORT
}
EOF
  sudo systemctl enable caddy >/dev/null 2>&1 || true
  sudo systemctl reload caddy 2>/dev/null || sudo systemctl restart caddy
  if command -v ufw >/dev/null && sudo ufw status | grep -q "Status: active"; then sudo ufw allow 80/tcp; fi
fi

step "Health check"
sleep 6
CODE=$(curl -s -o /dev/null -w "%{http_code}" "http://127.0.0.1:$PORT/panel/giris" || true)
echo "panel login page: HTTP $CODE (200 expected)"
IP=$(curl -fsS -4 --max-time 5 https://api.ipify.org 2>/dev/null || hostname -I | awk '{print $1}')

cat <<EOF

=============================================================
 Done.
   Server address : http://$IP
   Password       : $(cat "$APP_DIR/.bellekey")
   Web panel      : http://$IP/panel
   WhatsApp login : open WhatsBelle on the phone (or http://$IP/login)

 Enter the address and the password in each app's settings.
 Remember to open TCP port 80 in your cloud provider's firewall.
 Logs: pm2 logs belle-server     Restart: pm2 restart belle-server
=============================================================
EOF
